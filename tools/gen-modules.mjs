// Generates a layered graph of synthetic "feature" modules under src/generated/.
//
// The point is to get an app that is genuinely expensive in the two ways that
// matter for this experiment:
//   1. bytes  - each module carries a sizeable literal data table, so the
//               bundle takes real time to arrive over a throttled link.
//   2. eval   - each module does module-level init work (building indexes,
//               plus a calibrated spin), so evaluation is on the critical path.
//
// Everything is deterministic (seeded PRNG) so builds are reproducible and
// baseline/streamed comparisons measure the same work.

import {mkdirSync, rmSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'src', 'generated');

// SPIN_SCALE multiplies each module's evaluation-time busy work. 1 gives a
// bundle whose cost is mostly bytes (~1.3 s of evaluation in a debug build);
// 5 gives one whose cost is mostly evaluation (~5 s), which is the case
// streaming execution exists for.
const SPIN_SCALE = Number(process.env.SPIN_SCALE || 1);
// CYCLE=0 removes the svc_000 <-> svc_001 import cycle.
const CYCLE = process.env.CYCLE !== '0';

// Layer sizes: primitives -> services -> features -> screens.
const LAYERS = [
  {name: 'prim', count: 44, fanIn: 0, rows: 110, spin: 4},
  {name: 'svc', count: 60, fanIn: 3, rows: 130, spin: 6},
  {name: 'feat', count: 56, fanIn: 3, rows: 140, spin: 7},
  {name: 'screen', count: 16, fanIn: 5, rows: 90, spin: 5},
];

// ---------------------------------------------------------------- seeded PRNG
let seed = 0x9e3779b9;
function rnd() {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  seed >>>= 0;
  return seed / 0xffffffff;
}
const pick = (arr) => arr[Math.floor(rnd() * arr.length)];
const int = (lo, hi) => lo + Math.floor(rnd() * (hi - lo + 1));

const NOUNS = ['order', 'product', 'customer', 'shipment', 'refund', 'payout',
  'invoice', 'variant', 'inventory', 'discount', 'session', 'checkout',
  'fulfillment', 'subscription', 'payment', 'dispute', 'transfer', 'ledger'];
const ADJS = ['pending', 'settled', 'archived', 'draft', 'active', 'stale',
  'partial', 'flagged', 'verified', 'queued', 'expired', 'locked'];
const REGIONS = ['na-east', 'na-west', 'eu-central', 'eu-west', 'ap-south',
  'ap-northeast', 'sa-east', 'af-south'];
const CURRENCIES = ['USD', 'EUR', 'GBP', 'JPY', 'CAD', 'AUD', 'BRL', 'INR'];

function row(i) {
  return `  {k:'${pick(NOUNS)}_${pick(ADJS)}_${i}',region:'${pick(REGIONS)}',` +
    `currency:'${CURRENCIES[int(0, CURRENCIES.length - 1)]}',` +
    `amount:${int(100, 999999)},qty:${int(1, 240)},` +
    `weight:${(rnd() * 40).toFixed(4)},score:${(rnd() * 100).toFixed(3)},` +
    `flags:${int(0, 4095)},label:'${pick(ADJS)}-${pick(NOUNS)}-${i}'}`;
}

function moduleSource({layer, idx, deps, rows, spin, peer}) {
  const name = `${layer}_${String(idx).padStart(3, '0')}`;
  const table = Array.from({length: rows}, (_, i) => row(i)).join(',\n');
  const depImports = deps
    .map((d) => `import {compute_${d}, TABLE_${d}} from './${d.replace('_', '-')}.js';`)
    .join('\n');
  // A deliberate import cycle between two sibling modules, the way real
  // codebases end up with them. The cyclic binding is only used inside a
  // function, never at module top level, so evaluation order within the cycle
  // does not hit the TDZ.
  const peerImport = peer
    ? `import {compute_${peer}} from './${peer.replace('_', '-')}.js'; // cycle`
    : '';
  const depCalls = deps.map((d) => `compute_${d}(seedRow)`).join(' + ');
  const depTables = deps.map((d) => `TABLE_${d}.length`).join(' + ');

  return `// AUTO-GENERATED by tools/gen-modules.mjs - do not edit.
// layer=${layer} index=${idx} deps=${deps.length} rows=${rows}
import {sortBy, sumBy, groupBy} from 'lodash-es';
import {registerModule, spin, mixHash} from '../lib/runtime.js';
${depImports}
${peerImport}

export const TABLE_${name} = [
${table}
];

// Module-level init: the kind of work real modules do at evaluation time
// (building lookup structures, precomputing derived values).
const byRegion = groupBy(TABLE_${name}, 'region');
const ranked = sortBy(TABLE_${name}, (r) => -r.score).slice(0, 24);
const totalAmount = sumBy(TABLE_${name}, 'amount');
const index = new Map();
for (const r of TABLE_${name}) {
  index.set(r.k, {...r, norm: r.amount / (r.qty || 1), h: mixHash(r.k)});
}
spin(${(spin * SPIN_SCALE).toFixed(1)});

const seedRow = TABLE_${name}[0];

export function compute_${name}(input) {
  const base = mixHash(input ? input.k : '${name}') % 9973;
  const hit = index.get(input && input.k) || ranked[0];
  const local = base + (hit ? hit.flags : 0) + (totalAmount % 1021);
  ${deps.length ? `return local + (${depCalls});` : 'return local;'}
}

export function summarize_${name}() {
  return {
    name: '${name}',
    ${peer ? `peer: compute_${peer}(seedRow),` : ''}
    regions: Object.keys(byRegion).length,
    rows: TABLE_${name}.length,
    top: ranked.slice(0, 3).map((r) => r.label),
    totalAmount,
    ${deps.length ? `depRows: ${depTables},` : 'depRows: 0,'}
  };
}

export const meta_${name} = registerModule('${name}', {
  layer: '${layer}',
  index: ${idx},
  deps: ${JSON.stringify(deps)},
});
`;
}

// --------------------------------------------------------------------- build
rmSync(OUT, {recursive: true, force: true});
mkdirSync(OUT, {recursive: true});

const byLayer = [];
let total = 0;
let bytes = 0;

LAYERS.forEach((layerSpec, li) => {
  const names = [];
  const prev = li === 0 ? [] : byLayer[li - 1];
  for (let i = 0; i < layerSpec.count; i++) {
    const name = `${layerSpec.name}_${String(i).padStart(3, '0')}`;
    const deps = [];
    for (let d = 0; d < layerSpec.fanIn && prev.length; d++) {
      // Deterministic spread so the graph is wide rather than a chain.
      const cand = prev[(i * (layerSpec.fanIn + 1) + d * 7) % prev.length];
      if (!deps.includes(cand)) deps.push(cand);
    }
    const peer =
      CYCLE && layerSpec.name === 'svc' && i < 2
        ? `${layerSpec.name}_${String(1 - i).padStart(3, '0')}`
        : null;
    const src = moduleSource({
      layer: layerSpec.name,
      idx: i,
      deps,
      rows: layerSpec.rows,
      spin: layerSpec.spin,
      peer,
    });
    writeFileSync(join(OUT, `${layerSpec.name}-${String(i).padStart(3, '0')}.js`), src);
    bytes += Buffer.byteLength(src);
    names.push(name);
    total++;
  }
  byLayer.push(names);
});

// Barrel for the screens layer, which the app views import from.
const screens = byLayer[byLayer.length - 1];
writeFileSync(
  join(OUT, 'index.js'),
  `// AUTO-GENERATED by tools/gen-modules.mjs - do not edit.\n` +
    screens
      .map(
        (s) =>
          `export {compute_${s}, summarize_${s}, meta_${s}} from './${s.replace('_', '-')}.js';`,
      )
      .join('\n') +
    `\n\nexport const SCREEN_MODULES = ${JSON.stringify(screens, null, 2)};\n`,
);

console.log(
  `generated ${total} modules across ${LAYERS.length} layers, ` +
    `${(bytes / 1024 / 1024).toFixed(2)} MB of source in src/generated/ ` +
    `(SPIN_SCALE=${SPIN_SCALE}, cycle=${CYCLE ? 'svc_000<->svc_001' : 'none'})`,
);
